// Builds every output from the DTCG files in src/.
//
// Style Dictionary parses the DTCG files, resolves aliases and runs transforms.
// The outputs are written by the small formatters below, because each Figma
// mode needs its own CSS selector and the semantic tokens must stay as var()
// references so that brand, theme, platform and density can switch at runtime.
//
//   dist/css/tokens.css         all CSS variables, every mode
//   dist/tailwind/theme.css     Tailwind v4 @theme that maps utilities to the variables
//   dist/json/<mode>.json       resolved values per mode (used by the Storybook docs)
//   dist/ios/*.swift            SwiftUI constants (iOS platform values, light + dark colours)
//   dist/android/*.kt           Jetpack Compose constants (Android platform values)
import StyleDictionary from 'style-dictionary';
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = (f) => join(root, 'src', f);
const dist = (f) => join(root, 'dist', f);
const PREFIX = 'mds';
const BANNER = 'Generated by @rajaramasami/mds-tokens from the Master Design System Figma variables. Do not edit by hand.';

// ---------------------------------------------------------------------------
// Load one set of source files and return a flat list of resolved tokens.
// ---------------------------------------------------------------------------
async function load(files) {
  const sd = new StyleDictionary({
    source: files.map(src),
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: { flat: { transforms: ['name/kebab'] } },
  });
  const tree = await sd.exportPlatform('flat');
  const out = [];
  (function walk(node, path) {
    if (node && typeof node === 'object' && '$value' in node) {
      out.push({ path, name: path.join('-'), type: node.$type, value: node.$value, original: node.original.$value, file: node.filePath });
      return;
    }
    for (const [k, v] of Object.entries(node)) if (!k.startsWith('$')) walk(v, [...path, k]);
  })(tree, []);
  return out;
}
const fromFile = (tokens, f) => tokens.filter((t) => t.file.replace(/\\/g, '/').endsWith(`src/${f}`));

// ---------------------------------------------------------------------------
// CSS
// ---------------------------------------------------------------------------
const cssVar = (path) => `var(--${PREFIX}-${path.split('.').join('-')})`;
const isRef = (v) => typeof v === 'string' && /^\{[^}]+\}$/.test(v);
const FONT_STACKS = {
  'JetBrains Mono': '"JetBrains Mono", ui-monospace, SFMono-Regular, Menlo, monospace',
};
const fontStack = (f) => FONT_STACKS[f] ?? `"${f}", ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif`;

function cssValue(t, raw) {
  if (isRef(raw)) return cssVar(raw.slice(1, -1));
  switch (t.type) {
    case 'cubicBezier': return `cubic-bezier(${raw.join(', ')})`;
    case 'fontFamily': return fontStack(raw);
    default: return String(raw);
  }
}

function cssDecls(tokens) {
  const lines = [];
  for (const t of tokens) {
    if (t.type === 'typography') {
      for (const [k, v] of Object.entries(t.original)) {
        const prop = k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
        lines.push(`--${PREFIX}-${t.name}-${prop}: ${isRef(v) ? cssVar(v.slice(1, -1)) : v};`);
      }
    } else if (t.type === 'shadow') {
      const layers = t.original.map((l) => `${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${isRef(l.color) ? cssVar(l.color.slice(1, -1)) : l.color}`);
      lines.push(`--${PREFIX}-${t.name}: ${layers.join(', ')};`);
    } else {
      lines.push(`--${PREFIX}-${t.name}: ${cssValue(t, t.original)};`);
    }
  }
  return lines;
}
const block = (selector, tokens, indent = '') =>
  `${indent}${selector} {\n${cssDecls(tokens).map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}\n`;

// ---------------------------------------------------------------------------
// Swift and Kotlin helpers
// ---------------------------------------------------------------------------
const camel = (parts) => {
  const s = parts.join('-').replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  return /^[0-9]/.test(s) ? `_${s}` : s;
};
const px = (v) => Number(String(v).replace('px', ''));
const rgba = (hex) => {
  const h = hex.replace('#', '');
  return { r: h.slice(0, 2), g: h.slice(2, 4), b: h.slice(4, 6), a: h.length === 8 ? h.slice(6, 8) : 'ff' };
};
const swiftHex = (hex) => { const c = rgba(hex); return `0x${(c.r + c.g + c.b + c.a).toUpperCase()}`; };
const kotlinHex = (hex) => { const c = rgba(hex); return `0x${(c.a + c.r + c.g + c.b).toUpperCase()}`; };
// Drop the collection prefix that carries no meaning on the native side.
const nativeName = (t) => camel(t.path[0] === 'size' || t.path[0] === 'color' ? t.path.slice(1) : t.path);

function write(file, content) {
  mkdirSync(dirname(dist(file)), { recursive: true });
  writeFileSync(dist(file), content);
}

// ---------------------------------------------------------------------------
// Build
// ---------------------------------------------------------------------------
rmSync(join(root, 'dist'), { recursive: true, force: true });

const BASE = ['primitives.json', 'brand.json'];
const sets = {
  light: await load([...BASE, 'color/light.json']),
  dark: await load([...BASE, 'color/dark.json']),
  web: await load([...BASE, 'platform/web.json']),
  ios: await load([...BASE, 'platform/ios.json']),
  android: await load([...BASE, 'platform/android.json']),
  compact: await load([...BASE, 'density/compact.json']),
  comfortable: await load([...BASE, 'density/comfortable.json']),
  styles: await load([...BASE, 'color/light.json', 'platform/web.json', 'density/compact.json', 'styles.json']),
};

const primitives = fromFile(sets.light, 'primitives.json');
const brand = fromFile(sets.light, 'brand.json');
const mode = {
  light: fromFile(sets.light, 'color/light.json'),
  dark: fromFile(sets.dark, 'color/dark.json'),
  web: fromFile(sets.web, 'platform/web.json'),
  ios: fromFile(sets.ios, 'platform/ios.json'),
  android: fromFile(sets.android, 'platform/android.json'),
  compact: fromFile(sets.compact, 'density/compact.json'),
  comfortable: fromFile(sets.comfortable, 'density/comfortable.json'),
};
const styles = fromFile(sets.styles, 'styles.json');

// --- CSS -------------------------------------------------------------------
// Semantic tokens are re-declared wherever a mode attribute can change what
// they point at, so a nested [data-theme], [data-brand], [data-platform] or
// [data-density] scope works, not just the page root.
const css = [
  `/* ${BANNER} */\n`,
  `/* Primitives and brand ramp. Override the --${PREFIX}-brand-* variables on :root or on a [data-brand] element to re-theme a product. */`,
  block(':root', [...primitives, ...brand]),
  '/* Color: Light (default) */',
  block(':root,\n[data-theme="light"],\n[data-brand]', mode.light),
  '/* Color: Dark */',
  block('[data-theme="dark"],\n[data-theme="dark"] [data-brand]', mode.dark),
  '@media (prefers-color-scheme: dark) {',
  block(':root:not([data-theme="light"]),\n  :root:not([data-theme="light"]) [data-brand]', mode.dark, '  ') + '}\n',
  '/* Platform: Web (default) */',
  block(':root,\n[data-platform="web"]', mode.web),
  '/* Platform: iOS */',
  block('[data-platform="ios"]', mode.ios),
  '/* Platform: Android */',
  block('[data-platform="android"]', mode.android),
  '/* Density: Compact (default, as in Figma) */',
  block(':root,\n[data-density="compact"]', mode.compact),
  '/* Density: Comfortable */',
  block('[data-density="comfortable"]', mode.comfortable),
  '/* Text styles, elevation and focus rings. Re-declared in every mode scope so they pick up that scope\'s values. */',
  block(':root,\n[data-theme],\n[data-brand],\n[data-platform],\n[data-density]', styles),
].join('\n');
write('css/tokens.css', css);

// --- Tailwind v4 -------------------------------------------------------------
// `@theme inline` makes each utility use the CSS variable directly, so switching
// a mode attribute restyles everything without a rebuild. Tailwind's own palette,
// radii, shadows and text sizes are cleared so only semantic tokens are available.
const tw = [];
const map = (twName, t) => tw.push(`  --${twName}: var(--${PREFIX}-${t.name});`);
tw.push('  --color-*: initial;', '  --radius-*: initial;', '  --shadow-*: initial;', '  --text-*: initial;', '  --font-*: initial;', '  --ease-*: initial;', '  --blur-*: initial;');
tw.push('  --color-transparent: transparent;', '  --color-current: currentColor;');
for (const t of mode.light) map(`color-${t.path.slice(1).join('-')}`, t);
for (const t of mode.web) {
  const [head, ...rest] = t.path;
  if (head === 'typography') continue;
  if (head === 'radius') map(`radius-${rest.join('-')}`, t);
  else if (head === 'checkbox') map(`radius-checkbox`, t);
  else map(`spacing-${(head === 'size' ? rest : t.path).join('-')}`, t);
}
for (const t of mode.compact) map(`spacing-${(t.path[0] === 'size' ? t.path.slice(1) : t.path.slice(1)).join('-')}`, t);
for (const t of brand.filter((t) => t.type === 'fontFamily')) map(`font-${t.path.at(-1)}`, t);
for (const t of primitives.filter((t) => t.type === 'cubicBezier')) map(`ease-${t.path.at(-1)}`, t);
for (const t of styles) {
  if (t.type === 'typography') {
    const n = t.path.slice(1).join('-');
    tw.push(
      `  --text-${n}: var(--${PREFIX}-${t.name}-font-size);`,
      `  --text-${n}--line-height: var(--${PREFIX}-${t.name}-line-height);`,
      `  --text-${n}--letter-spacing: var(--${PREFIX}-${t.name}-letter-spacing);`,
      `  --text-${n}--font-weight: var(--${PREFIX}-${t.name}-font-weight);`,
    );
  } else if (t.type === 'shadow') map(`shadow-${t.path.join('-')}`, t);
  else if (t.path[0] === 'blur') map(`blur-${t.path.slice(1).join('-')}`, t);
}
write('tailwind/theme.css', `/* ${BANNER} */\n/* Use after @import "tailwindcss" and the tokens CSS. */\n@theme inline {\n${tw.join('\n')}\n}\n`);

// --- JSON (resolved values per mode, for docs and tests) ------------------------
const flat = (tokens) => Object.fromEntries(tokens.map((t) => [`--${PREFIX}-${t.name}`, t.value]));
write('json/primitives.json', JSON.stringify(flat(primitives), null, 2));
write('json/brand.json', JSON.stringify(flat(brand), null, 2));
for (const [m, tokens] of Object.entries(mode)) write(`json/${m}.json`, JSON.stringify(flat(tokens), null, 2));

// --- Swift (SwiftUI) -------------------------------------------------------------
const darkByName = Object.fromEntries(mode.dark.map((t) => [t.name, t.value]));
write('ios/MDSColor.swift', `// ${BANNER}
import SwiftUI
import UIKit

public enum MDSColor {
${mode.light.map((t) => `    public static let ${nativeName(t)} = Color(light: ${swiftHex(t.value)}, dark: ${swiftHex(darkByName[t.name])})`).join('\n')}
}

extension Color {
    /// A colour that follows the system light or dark appearance. Values are 0xRRGGBBAA.
    init(light: UInt32, dark: UInt32) {
        self.init(UIColor { traits in
            UIColor(rgba: traits.userInterfaceStyle == .dark ? dark : light)
        })
    }
}

extension UIColor {
    convenience init(rgba: UInt32) {
        self.init(
            red: CGFloat((rgba >> 24) & 0xFF) / 255,
            green: CGFloat((rgba >> 16) & 0xFF) / 255,
            blue: CGFloat((rgba >> 8) & 0xFF) / 255,
            alpha: CGFloat(rgba & 0xFF) / 255
        )
    }
}
`);
write('ios/MDSPlatform.swift', `// ${BANNER}
import CoreGraphics

/// iOS values from the Platform collection (sizes, radii, type scale).
public enum MDSPlatform {
${mode.ios.map((t) => `    public static let ${nativeName(t)}: CGFloat = ${px(t.value)}`).join('\n')}
}
`);
const densityFields = mode.compact.map((t) => nativeName(t));
const densityInit = (tokens) => tokens.map((t) => `${nativeName(t)}: ${px(t.value)}`).join(', ');
write('ios/MDSDensity.swift', `// ${BANNER}
import CoreGraphics

/// Spacing and row heights from the Density collection.
public struct MDSDensity {
${densityFields.map((f) => `    public let ${f}: CGFloat`).join('\n')}

    public static let compact = MDSDensity(${densityInit(mode.compact)})
    public static let comfortable = MDSDensity(${densityInit(mode.comfortable)})
}
`);

// --- Kotlin (Jetpack Compose) ------------------------------------------------------
const kColors = (tokens) => tokens.map((t) => `    val ${nativeName(t)} = Color(${kotlinHex(t.value)})`).join('\n');
write('android/MDSColor.kt', `// ${BANNER}
package design.mds.tokens

import androidx.compose.ui.graphics.Color

object MDSLightColors {
${kColors(mode.light)}
}

object MDSDarkColors {
${kColors(mode.dark)}
}
`);
const isFont = (t) => /font-size|line-height/.test(t.name);
write('android/MDSPlatform.kt', `// ${BANNER}
package design.mds.tokens

import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/** Android values from the Platform collection (sizes, radii, type scale). */
object MDSPlatform {
${mode.android.map((t) => `    val ${nativeName(t)} = ${px(t.value)}.${isFont(t) ? 'sp' : 'dp'}`).join('\n')}
}
`);
const kDensity = (tokens) => tokens.map((t) => `        ${nativeName(t)} = ${px(t.value)}.dp`).join(',\n');
write('android/MDSDensity.kt', `// ${BANNER}
package design.mds.tokens

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/** Spacing and row heights from the Density collection. */
data class MDSDensity(
${densityFields.map((f) => `    val ${f}: Dp`).join(',\n')}
) {
    companion object {
        val Compact = MDSDensity(
${kDensity(mode.compact)}
        )
        val Comfortable = MDSDensity(
${kDensity(mode.comfortable)}
        )
    }
}
`);

const total = primitives.length + brand.length + mode.light.length + mode.web.length + mode.compact.length;
console.log(`Built ${total} tokens (${primitives.length} primitives, ${brand.length} brand, ${mode.light.length} colour, ${mode.web.length} platform, ${mode.compact.length} density) + ${styles.length} styles.`);
